"""
`pnwtools.Undo_Rename`

Undo a previous file renaming operation. Requires a rename_log file, as 
generated by pnwtools.Rename_Files.
"""

import argparse
from pathlib import Path
from pnwtools.utils.naming import *


def _build_parser():
    parser = argparse.ArgumentParser(description="Undo the results of a previous file renaming operation.")

    parser.add_argument("log_file",
                        type=str,
                        help="Path to a rename_log file previously generated by pnwtools.Rename_Files.")

    return parser


def main():
    parser = _build_parser()
    args = parser.parse_args()

    log_path = Path(args.log_file)
    if not log_path.exists():
        print("\nPlease provide a valid path to a rename_log file.")
        exit()
    else:
        try:
            log_info = read_rename_log(log_path)
        except:
            print("\nCould not read rename log file.")
            exit()

    n_changes = sum([1 for i in log_info if i[-1] == "1"])
    print(f"\nAttempting to revert {n_changes} previously renamed files.") 
    result = mass_rename(log_info, reverse=True)

    errors = [r for r in result if r[3] == -1]
    if len(errors) > 1:
        print(f"\nCould not revert {len(errors)} filenames: ")


if __name__ == "__main__":
    main()

